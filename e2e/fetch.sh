#!/usr/bin/env bash
# Downloads the third-party files the e2e kit needs into E2E_CACHE (default e2e/work/cache). Every download is
# checked against a pinned SHA-256 and kept only if it matches. Idempotent: files that are already there with the right
# SHA-256 are kept. run_e2e.sh calls this itself.
#
#   fetch.sh [server] [mods] [velocity] [jre25] [viafabric] [polymer-real]       default: server mods
#
#   server        Fabric server launcher for 1.21.11 and E2E_LOADER (0.19.5 default; 0.19.3, 0.19.0 and 0.18.6 are
#                 pinned too), plus a server template: the launcher's first run downloads and remaps Minecraft, which
#                 every scenario then reuses, and downloads the Loader and its libraries from maven.fabricmc.net, which
#                 are checked against the SHA-256 pins below. Needs ACCEPT_EULA=true.
#   mods          Fabric API, Polymer (bundled), FabricProxy-Lite
#   velocity      Velocity 4.2.0 (needs Java 25)
#   jre25         a Temurin 25 JRE for Velocity (skipped if the cache has one, or VELOCITY_JAVA / JAVA is Java 25)
#   viafabric     ViaFabric 0.4.21+166 (bundles ViaVersion 5.10.0), for the V* scenarios
#   polymer-real  PolyDecorations and PolyFactory 0.10.4, real Polymer-based mods, for the PR* and PL2 scenarios
#
# Not covered by these pins: the Minecraft server jar and libraries the launcher downloads for the template (Mojang's
# manifest checksums apply), and the Gradle artifacts of the test mods (see README.md).
set -euo pipefail

E2E_PROG=fetch.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
e2e_defaults
CACHE=$E2E_CACHE
mkdir -p "$CACHE"

# fetch <file name in cache> <url> <sha256>
fetch() {
  local file=$CACHE/$1
  if [ -f "$file" ] && [ "$(sha256sum "$file" | cut -d' ' -f1)" = "$3" ]; then
    return
  fi
  echo "fetch.sh: downloading $1"
  curl -fsSL --retry 3 -o "$file.part" "$2"
  if [ "$(sha256sum "$file.part" | cut -d' ' -f1)" != "$3" ]; then
    rm -f "$file.part"
    echo "fetch.sh: checksum mismatch for $1 (downloaded from $2)" >&2
    exit 1
  fi
  mv "$file.part" "$file"
}

