# verify_loader_libraries <template dir> <loader>: every jar above is there with its pinned SHA-256
verify_loader_libraries() {
  local template=$1 loader=$2 path sha bad=0
  while read -r path sha; do
    if [ "$(sha256sum "$template/libraries/$path" 2>/dev/null | cut -d' ' -f1)" != "$sha" ]; then
      echo "fetch.sh: libraries/$path in the server template is missing or does not match its pinned SHA-256 $sha" >&2
      bad=1
    fi
  done < <(loader_library_pins "$loader")
  return $bad
}


fetch_server() {
  local loader=$E2E_LOADER launcher sha template
  launcher=fabric-server-launch-1.21.11-$loader.jar
  sha=$(launcher_sha256 "$loader")
  fetch "$launcher" "https://meta.fabricmc.net/v2/versions/loader/1.21.11/$loader/1.1.2/server/jar" "$sha"
  template=$(template_dir)
  if [ -d "$template/libraries" ] && [ -d "$template/versions" ]; then
    if ! verify_loader_libraries "$template" "$loader"; then
      echo "fetch.sh: removing the server template $template; run fetch.sh again to build it anew" >&2
      rm -rf "$template"
      exit 1
    fi
    return
  fi
  if [ "${ACCEPT_EULA:-}" != "true" ]; then
    echo "fetch.sh: running a Minecraft server means accepting the Minecraft EULA (https://aka.ms/MinecraftEULA)." >&2
    echo "          Re-run with ACCEPT_EULA=true if you accept it." >&2
    exit 1
  fi
  echo "fetch.sh: preparing the server template for loader $loader (downloads and remaps Minecraft 1.21.11, takes a minute)"
  rm -rf "$template"
  mkdir -p "$template"
  local default_template=$CACHE/server-template
  if [ "$loader" != "$DEFAULT_LOADER" ] && [ -d "$default_template/libraries" ]; then
    # Start from the default loader's template (Mojang's server jar and the vanilla libraries are already there) and
    # drop everything that belongs to that loader.
    cp -a "$default_template/." "$template/"
    rm -rf "$template/logs" "$template/.fabric/remappedJars" "$template/.fabric/processedMods" "$template"/.fabric/server/fabric-loader-server-*
  fi
  cp "$CACHE/$launcher" "$template/fabric-server-launch.jar"
  echo "eula=true" > "$template/eula.txt"
  # --initSettings makes the server write its settings files and exit before it loads a world.
  (cd "$template" && "$JAVA" -jar fabric-server-launch.jar nogui --initSettings > launch.log 2>&1 < "$E2E_STDIN") || {
    echo "fetch.sh: the server template run failed, see $template/launch.log" >&2
    exit 1
  }
  rm -rf "$template/server.properties" "$template/launch.log" "$template/logs"
  if ! verify_loader_libraries "$template" "$loader"; then
    echo "fetch.sh: removing the server template $template" >&2
    rm -rf "$template"
    exit 1
  fi
}

